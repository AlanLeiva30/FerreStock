// ─────────────────────────────────────────────────────────────
// CHAT DEL EQUIPO: una sala para todos y conversaciones privadas entre dos personas
// ─────────────────────────────────────────────────────────────
// Hay dos tipos de conversación, y los dos usan la tabla "mensajes":
//   · GLOBAL:   para_id vacío. La ven todas las personas del sistema.
//   · PRIVADA:  para_id = la otra persona. Solo la ven esas dos personas: ni el administrador puede leerla.
// Reglas:
//   · Recibos (como WhatsApp): cada mensaje tiene sus tres estados: ENVIADO (llegó al servidor), ENTREGADO (la otra persona
//     tiene el programa abierto y su pantalla lo recibió) y LEÍDO (abrió esa conversación). Con la hora de cada uno.
//     En un chat privado se guardan en el propio mensaje ("entregado_en" y "leido_en"); en la sala global, de cada
//     persona en la tabla "mensajes_lecturas". Solo quien escribió el mensaje ve su información.
//   · Menciones: en la sala global se puede escribir @Nombre para dirigir el mensaje a alguien. El mensaje se guarda con
//     la lista de las personas mencionadas ("menciones"); a ellas les aparece resaltado y con una «@» en los no leídos.
//   · Solo texto, máximo 500 caracteres. Hay un límite de envíos por minuto para no llenar el chat.
//   · En la sala global, cada persona borra sus mensajes y el administrador cualquiera. En las privadas,
//     solo quien escribió el mensaje. Al borrar, el texto se borra de la base (queda «Mensaje eliminado»).
//   · No leídos: en la sala global, "usuarios.chat_visto" guarda el último mensaje que la persona vio.
//     En las privadas, cada mensaje guarda cuándo lo leyó la otra persona ("leido_en"), que también sirve para el «Visto».
// Las tablas y columnas se crean solas al arrancar el servidor si faltan.
import {bd, consultar} from '../basedatos/baseDeDatos.js';
import {CODIGOS, ErrorParaElUsuario, texto} from '../comun/http.js';
import {ADMINISTRADOR, conNombreDeRol} from '../acceso/roles.js';
const LARGO_MAXIMO = 500;
const MENSAJES_POR_PAGINA = 50;
const MAXIMO_POR_MINUTO = 20; // envíos por persona
const envios = new Map(); // id de la persona → momentos de sus últimos envíos
const tablaLista = (async () => {
  await consultar(`CREATE TABLE IF NOT EXISTS public.mensajes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint REFERENCES public.usuarios(id) ON DELETE SET NULL,
    autor text NOT NULL,
    texto text NOT NULL CHECK (char_length(texto) BETWEEN 1 AND ${LARGO_MAXIMO}),
    fecha timestamptz NOT NULL DEFAULT now(),
    eliminado timestamptz
  )`);
  await consultar('ALTER TABLE public.mensajes ENABLE ROW LEVEL SECURITY');
  await consultar('ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS chat_visto bigint NOT NULL DEFAULT 0');
  // Chats privados. Si se elimina a la otra persona, sus conversaciones se borran con ella (CASCADE):
  // con SET NULL un mensaje privado se convertiría en uno de la sala global.
  await consultar('ALTER TABLE public.mensajes ADD COLUMN IF NOT EXISTS para_id bigint REFERENCES public.usuarios(id) ON DELETE CASCADE');
  await consultar('ALTER TABLE public.mensajes ADD COLUMN IF NOT EXISTS leido_en timestamptz');
  await consultar("ALTER TABLE public.mensajes ADD COLUMN IF NOT EXISTS menciones jsonb NOT NULL DEFAULT '[]'::jsonb");
  // Recibos de entrega y lectura. "recibos" es verdadero en los mensajes nuevos; los anteriores no tienen ese registro.
  await consultar('ALTER TABLE public.mensajes ADD COLUMN IF NOT EXISTS entregado_en timestamptz, ADD COLUMN IF NOT EXISTS recibos boolean NOT NULL DEFAULT false');
  await consultar(`CREATE TABLE IF NOT EXISTS public.mensajes_lecturas (
    mensaje_id bigint NOT NULL REFERENCES public.mensajes(id) ON DELETE CASCADE,
    usuario_id bigint NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    entregado_en timestamptz NOT NULL DEFAULT now(),
    leido_en timestamptz,
    PRIMARY KEY (mensaje_id, usuario_id)
  )`);
  await consultar('ALTER TABLE public.mensajes_lecturas ENABLE ROW LEVEL SECURITY');
  await consultar('CREATE INDEX IF NOT EXISTS idx_mensajes_privados ON public.mensajes (para_id, usuario_id, id)');
})().catch(error => {
  console.error('[FerreStock] No se pudo preparar el chat:', error.code || error.message);
});
// Lo que se manda a la pantalla: los mensajes borrados salen sin texto.
const publico = (fila, destinatarios = 0) => ({
  id: Number(fila.id),
  usuario_id: fila.usuario_id === null ? null : Number(fila.usuario_id),
  para_id: fila.para_id === null || fila.para_id === undefined ? null : Number(fila.para_id),
  autor: fila.autor,
  texto: fila.eliminado ? null : fila.texto,
  eliminado: !!fila.eliminado,
  menciones: Array.isArray(fila.menciones) ? fila.menciones.map(Number) : [],
  visto: fila.para_id ? fila.leido_en !== null && fila.leido_en !== undefined : null,
  // Recibos: en un privado, la hora de entrega y de lectura; en la sala global (solo en tus mensajes), cuántas personas lo recibieron y lo leyeron
  // y quiénes ("lectores": los números de las personas que lo leyeron, en el orden en que lo hicieron).
  entregado_en: fila.para_id ? fila.entregado_en ?? fila.leido_en ?? null : null,
  leido_en: fila.para_id ? fila.leido_en ?? null : null,
  recibos: fila.para_id === null || fila.para_id === undefined
    ? (fila.n_entregados === null || fila.n_entregados === undefined || !fila.recibos ? null : {total: destinatarios, entregados: Number(fila.n_entregados), leidos: Number(fila.n_leidos), lectores: Array.isArray(fila.lectores) ? fila.lectores.map(Number) : []})
    : null,
  fecha: fila.fecha
});
function entero(valor, mensaje) {
  if (valor === null || valor === undefined || valor === '') return null;
  const n = Number(valor);
  if (!Number.isInteger(n) || n < 0) throw new ErrorParaElUsuario(CODIGOS.DATOS_INCORRECTOS, mensaje);
  return n;
}
// Cuántas personas pueden recibir un mensaje de la sala global (todas las activas menos quien lo escribió).
async function totalDeDestinatarios() {
  const {rows} = await consultar('SELECT COUNT(*) AS n FROM usuarios WHERE activo = 1 AND eliminado IS NULL');
  return Math.max(Number(rows[0].n) - 1, 0);
}
// Marca como ENTREGADOS los mensajes que le llegaron a esta persona (porque tiene el programa abierto): los privados que le
// escribieron y los de la sala global que todavía no ha leído. Se llama cada vez que su pantalla consulta el chat.
async function registrarEntregas(usuario) {
  await consultar('UPDATE mensajes SET entregado_en = now() WHERE para_id = $1 AND entregado_en IS NULL', [usuario.id]);
  await consultar(`
    INSERT INTO mensajes_lecturas (mensaje_id, usuario_id)
    SELECT m.id, $1 FROM mensajes m
    WHERE m.para_id IS NULL AND m.recibos AND m.eliminado IS NULL AND m.usuario_id IS DISTINCT FROM $1
      AND m.fecha > now() - interval '30 days' AND m.id > (SELECT chat_visto FROM usuarios WHERE id = $1)
    ON CONFLICT (mensaje_id, usuario_id) DO NOTHING`, [usuario.id]);
}
// Los mensajes de una conversación. "con" = el número de la otra persona (sin "con": la sala global).
// Sin más parámetros: los últimos 50. "desde": los que llegaron después de ese número.
// "antes": 50 mensajes anteriores a ese número (para «ver mensajes anteriores»).
export async function listarMensajes(parametros, usuario) {
  await tablaLista;
  const aviso = 'Los datos del chat no son válidos';
  const desde = entero(parametros.get('desde'), aviso);
  const antes = entero(parametros.get('antes'), aviso);
  const con = entero(parametros.get('con'), aviso);
  await registrarEntregas(usuario);
  const valores = [];
  const agregar = valor => '$' + valores.push(valor);
  // En la sala global, de tus propios mensajes se cuenta cuántas personas los recibieron y los leyeron.
  const yo = agregar(usuario.id);
  const columnas = `m.*,
    CASE WHEN m.para_id IS NULL AND m.usuario_id = ${yo} THEN (SELECT COUNT(*) FROM mensajes_lecturas l WHERE l.mensaje_id = m.id) END AS n_entregados,
    CASE WHEN m.para_id IS NULL AND m.usuario_id = ${yo} THEN (SELECT COUNT(*) FROM mensajes_lecturas l WHERE l.mensaje_id = m.id AND l.leido_en IS NOT NULL) END AS n_leidos,
    CASE WHEN m.para_id IS NULL AND m.usuario_id = ${yo} THEN (SELECT COALESCE(jsonb_agg(l.usuario_id ORDER BY l.leido_en), '[]'::jsonb) FROM mensajes_lecturas l WHERE l.mensaje_id = m.id AND l.leido_en IS NOT NULL) END AS lectores`;
  // Una conversación privada solo incluye mensajes entre "yo" y "la otra persona"; la global, los que no tienen destinatario.
  const donde = con === null
    ? ['m.para_id IS NULL']
    : [`m.para_id IS NOT NULL AND ((m.usuario_id = ${yo} AND m.para_id = ${agregar(con)}) OR (m.usuario_id = ${agregar(con)} AND m.para_id = ${yo}))`];
  const destinatarios = await totalDeDestinatarios();
  if (desde !== null) {
    donde.push(`m.id > ${agregar(desde)}`);
    const {rows} = await consultar(`SELECT ${columnas} FROM mensajes m WHERE ${donde.join(' AND ')} ORDER BY m.id LIMIT 200`, valores);
    return {mensajes: rows.map(fila => publico(fila, destinatarios)), hayMas: false};
  }
  if (antes !== null) donde.push(`m.id < ${agregar(antes)}`);
  const {rows} = await consultar(`SELECT ${columnas} FROM mensajes m WHERE ${donde.join(' AND ')} ORDER BY m.id DESC LIMIT ${MENSAJES_POR_PAGINA + 1}`, valores);
  const hayMas = rows.length > MENSAJES_POR_PAGINA;
  return {mensajes: rows.slice(0, MENSAJES_POR_PAGINA).reverse().map(fila => publico(fila, destinatarios)), hayMas};
}
// "para" (opcional) = a quién va el mensaje privado. Sin "para" se publica en la sala global.
export async function enviarMensaje(datos, usuario) {
  await tablaLista;
  const mensaje = texto(datos?.texto).replace(/\r\n?/g, '\n').replace(/\n{3,}/g, '\n\n');
  if (!mensaje) throw new ErrorParaElUsuario(CODIGOS.DATOS_INCORRECTOS, 'Escribe un mensaje');
  if (mensaje.length > LARGO_MAXIMO) throw new ErrorParaElUsuario(CODIGOS.DATOS_INCORRECTOS, `El mensaje es muy largo (máximo ${LARGO_MAXIMO} caracteres)`);
  const para = entero(datos?.para, 'La persona a la que le escribes no es válida');
  if (para !== null) {
    if (para === usuario.id) throw new ErrorParaElUsuario(CODIGOS.DATOS_INCORRECTOS, 'No puedes escribirte a ti mismo');
    const {rows} = await consultar('SELECT id FROM usuarios WHERE id = $1 AND activo = 1 AND eliminado IS NULL', [para]);
    if (!rows.length) throw new ErrorParaElUsuario(CODIGOS.NO_EXISTE, 'Esa persona no está disponible');
  }
  // Menciones (@Nombre): solo en la sala global, hasta 10 personas, todas activas.
  let menciones = [];
  if (datos?.menciones !== undefined && datos.menciones !== null) {
    if (!Array.isArray(datos.menciones) || datos.menciones.length > 10) throw new ErrorParaElUsuario(CODIGOS.DATOS_INCORRECTOS, 'Las personas mencionadas no son válidas');
    menciones = [...new Set(datos.menciones.map(Number))];
    if (menciones.some(id => !Number.isInteger(id) || id < 1)) throw new ErrorParaElUsuario(CODIGOS.DATOS_INCORRECTOS, 'Las personas mencionadas no son válidas');
    if (para !== null && menciones.length) menciones = [];
    if (menciones.length) {
      const {rows} = await consultar('SELECT id FROM usuarios WHERE id = ANY($1::bigint[]) AND activo = 1 AND eliminado IS NULL', [menciones]);
      if (rows.length !== menciones.length) throw new ErrorParaElUsuario(CODIGOS.NO_EXISTE, 'Alguna de las personas mencionadas no está disponible');
    }
  }
  const ahora = Date.now();
  const recientes = (envios.get(usuario.id) ?? []).filter(momento => ahora - momento < 60_000);
  if (recientes.length >= MAXIMO_POR_MINUTO) throw new ErrorParaElUsuario(CODIGOS.DEMASIADOS_INTENTOS, 'Estás enviando muchos mensajes. Espera un momento.');
  recientes.push(ahora);
  envios.set(usuario.id, recientes);
  const {rows} = await consultar('INSERT INTO mensajes (usuario_id, para_id, autor, texto, menciones, recibos) VALUES ($1, $2, $3, $4, $5::jsonb, true) RETURNING *', [usuario.id, para, usuario.nombre, mensaje, JSON.stringify(menciones)]);
  const nuevo = rows[0];
  // Recién enviado: ya "llegó al servidor" (un ✓) y todavía nadie lo ha recibido ni leído.
  return publico({...nuevo, n_entregados: para === null ? 0 : null, n_leidos: para === null ? 0 : null, lectores: []}, para === null ? await totalDeDestinatarios() : 0);
}
export async function borrarMensaje(id, usuario) {
  await tablaLista;
  const {rows} = await consultar('SELECT id, usuario_id, para_id FROM mensajes WHERE id = $1 FOR UPDATE', [id]);
  const mensaje = rows[0];
  const esMio = mensaje && Number(mensaje.usuario_id) === usuario.id;
  // En una conversación privada el administrador no ve los mensajes de otras personas, así que tampoco puede borrarlos.
  const privado = mensaje && mensaje.para_id !== null;
  if (!mensaje || privado && !esMio && Number(mensaje.para_id) !== usuario.id) throw new ErrorParaElUsuario(CODIGOS.NO_EXISTE, 'Mensaje no encontrado');
  if (!esMio && (privado || usuario.rol !== ADMINISTRADOR)) {
    throw new ErrorParaElUsuario(CODIGOS.PROHIBIDO, 'Solo puedes borrar tus propios mensajes');
  }
  // Se borra de verdad el contenido (queda un guion), no solo se oculta.
  await consultar("UPDATE mensajes SET eliminado = now(), texto = '—' WHERE id = $1 AND eliminado IS NULL", [id]);
  return {id};
}
// Cuántos mensajes sin leer tiene la persona: de la sala global, de cada persona en privado y el total (el globo del ícono).
export async function resumenDelChat(usuario) {
  await tablaLista;
  await registrarEntregas(usuario); // si tu pantalla está consultando, los mensajes nuevos ya te llegaron (✓✓)
  const global = await consultar(`
    SELECT COUNT(*) AS n FROM mensajes m
    WHERE m.para_id IS NULL AND m.eliminado IS NULL AND m.usuario_id IS DISTINCT FROM $1
      AND m.id > (SELECT chat_visto FROM usuarios WHERE id = $1)`, [usuario.id]);
  const privados = await consultar(`
    SELECT usuario_id AS de, COUNT(*) AS n FROM mensajes
    WHERE para_id = $1 AND leido_en IS NULL AND eliminado IS NULL AND usuario_id IS NOT NULL
    GROUP BY usuario_id`, [usuario.id]);
  const porPersona = Object.fromEntries(privados.rows.map(fila => [Number(fila.de), Number(fila.n)]));
  const noLeidosPrivados = Object.values(porPersona).reduce((suma, n) => suma + n, 0);
  const noLeidos = Number(global.rows[0].n);
  // De los mensajes globales sin leer, en cuántos te mencionaron a ti (@).
  const menciones = await consultar(`
    SELECT COUNT(*) AS n FROM mensajes m
    WHERE m.para_id IS NULL AND m.eliminado IS NULL AND m.usuario_id IS DISTINCT FROM $1
      AND m.id > (SELECT chat_visto FROM usuarios WHERE id = $1) AND m.menciones @> to_jsonb($1::bigint)`, [usuario.id]);
  return {noLeidos, menciones: Number(menciones.rows[0].n), privados: porPersona, noLeidosPrivados, total: noLeidos + noLeidosPrivados};
}
// La lista de conversaciones (la ventanita flotante): la sala global y una fila por cada persona activa,
// con su último mensaje, cuántos no ha leído y si está en línea (la hora de su última conexión).
export async function listarConversaciones(usuario) {
  await tablaLista;
  const personas = await consultar(`
    SELECT u.id, u.nombre, u.rol, u.sexo, u.foto, u.ultima_conexion,
      (SELECT COUNT(*) FROM mensajes m WHERE m.para_id = $1 AND m.usuario_id = u.id AND m.leido_en IS NULL AND m.eliminado IS NULL) AS no_leidos,
      u2.texto AS ultimo_texto, u2.fecha AS ultimo_fecha, u2.mio AS ultimo_mio, u2.eliminado AS ultimo_eliminado
    FROM usuarios u
    LEFT JOIN LATERAL (
      SELECT m.texto, m.fecha, m.eliminado, (m.usuario_id = $1) AS mio FROM mensajes m
      WHERE m.para_id IS NOT NULL AND ((m.usuario_id = $1 AND m.para_id = u.id) OR (m.usuario_id = u.id AND m.para_id = $1))
      ORDER BY m.id DESC LIMIT 1) u2 ON true
    WHERE u.activo = 1 AND u.eliminado IS NULL AND u.id <> $1
    ORDER BY u2.fecha DESC NULLS LAST, u.nombre`, [usuario.id]);
  const ultimoGlobal = await consultar('SELECT autor, texto, fecha, eliminado FROM mensajes WHERE para_id IS NULL ORDER BY id DESC LIMIT 1');
  const resumen = await resumenDelChat(usuario);
  const ultimo = ultimoGlobal.rows[0];
  return {
    global: {
      noLeidos: resumen.noLeidos,
      menciones: resumen.menciones,
      ultimo: ultimo ? {autor: ultimo.autor, texto: ultimo.eliminado ? null : ultimo.texto, fecha: ultimo.fecha} : null
    },
    personas: personas.rows.map(fila => {
      const {sexo, ...persona} = conNombreDeRol({id: Number(fila.id), nombre: fila.nombre, rol: fila.rol, sexo: fila.sexo, foto: fila.foto, ultima_conexion: fila.ultima_conexion});
      return {
        ...persona,
        noLeidos: Number(fila.no_leidos),
        ultimo: fila.ultimo_fecha ? {texto: fila.ultimo_eliminado ? null : fila.ultimo_texto, fecha: fila.ultimo_fecha, mio: fila.ultimo_mio} : null
      };
    })
  };
}
// «Ya leí todo»: sin datos, la sala global; con {con: id}, la conversación privada con esa persona.
export async function marcarChatComoLeido(datos, usuario) {
  await tablaLista;
  const con = entero(datos?.con, 'Los datos del chat no son válidos');
  if (con === null) {
    // Cada mensaje nuevo de la sala se anota como leído por esta persona, con su hora.
    await consultar(`
      INSERT INTO mensajes_lecturas (mensaje_id, usuario_id, leido_en)
      SELECT m.id, $1, now() FROM mensajes m
      WHERE m.para_id IS NULL AND m.recibos AND m.eliminado IS NULL AND m.usuario_id IS DISTINCT FROM $1
        AND m.id > (SELECT chat_visto FROM usuarios WHERE id = $1)
      ON CONFLICT (mensaje_id, usuario_id) DO UPDATE SET leido_en = COALESCE(mensajes_lecturas.leido_en, now())`, [usuario.id]);
    await consultar('UPDATE usuarios SET chat_visto = (SELECT COALESCE(MAX(id), 0) FROM mensajes WHERE para_id IS NULL) WHERE id = $1', [usuario.id]);
  } else {
    await consultar('UPDATE mensajes SET leido_en = now(), entregado_en = COALESCE(entregado_en, now()) WHERE para_id = $1 AND usuario_id = $2 AND leido_en IS NULL', [usuario.id, con]);
  }
  return {ok: true};
}
// «Info del mensaje» (solo para quien lo escribió): a quién le llegó y quién lo leyó, con la hora de cada cosa.
export async function infoDelMensaje(id, usuario) {
  await tablaLista;
  const {rows} = await consultar('SELECT * FROM mensajes WHERE id = $1', [id]);
  const mensaje = rows[0];
  if (!mensaje || Number(mensaje.usuario_id) !== usuario.id) throw new ErrorParaElUsuario(CODIGOS.NO_EXISTE, 'Mensaje no encontrado');
  if (mensaje.eliminado) throw new ErrorParaElUsuario(CODIGOS.DATOS_INCORRECTOS, 'Este mensaje fue eliminado');
  if (mensaje.para_id !== null) {
    const persona = await consultar('SELECT id, nombre, rol, sexo FROM usuarios WHERE id = $1', [mensaje.para_id]);
    return {
      id, fecha: mensaje.fecha, global: false, conRecibos: mensaje.recibos || mensaje.leido_en !== null,
      destinatarios: persona.rows.map(fila => ({...conNombreDeRol(fila), sexo: undefined, entregado_en: mensaje.entregado_en ?? mensaje.leido_en ?? null, leido_en: mensaje.leido_en ?? null}))
    };
  }
  const personas = await consultar(`
    SELECT u.id, u.nombre, u.rol, u.sexo, l.entregado_en, l.leido_en
    FROM usuarios u LEFT JOIN mensajes_lecturas l ON l.mensaje_id = $1 AND l.usuario_id = u.id
    WHERE u.activo = 1 AND u.eliminado IS NULL AND u.id <> $2
    ORDER BY l.leido_en NULLS LAST, l.entregado_en NULLS LAST, u.nombre`, [id, usuario.id]);
  return {
    id, fecha: mensaje.fecha, global: true, conRecibos: mensaje.recibos,
    destinatarios: personas.rows.map(fila => ({...conNombreDeRol(fila), sexo: undefined, entregado_en: fila.entregado_en ?? null, leido_en: fila.leido_en ?? null}))
  };
}
